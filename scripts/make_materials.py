"""Generate ForeverJunkItems/Data/Materials.lua from WoW Forever's game tables.

    python scripts/make_materials.py [--build 1.60.1.70959] [--cache .cache/db2]

Reads the client tables published by wago.tools for the Forever product
(`wowf`): SkillLine (profession names in every client language),
SkillLineAbility (which spells belong to which profession), SpellReagents
(what those spells consume) and Item (class and subclass of every item).
A material belongs to a profession when one of that profession's recipes
consumes it. Gathering professions (Herbalism, Skinning, Mining) also own
what they gather, by Trade Goods subclass.

Run it again after every Forever patch. Python 3 standard library only.
"""
import argparse
import csv
import io
import pathlib
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "ForeverJunkItems" / "Data" / "Materials.lua"
DEFAULT_BUILD = "1.60.1.70959"
LOCALES = ["enUS", "deDE", "frFR", "esES", "esMX", "ptBR", "ruRU", "koKR", "zhCN", "zhTW"]

# Skill line -> stable key. Forever adds a child line per profession
# (2937-2948) whose parent is the classic line; both map to the same key.
PROFESSIONS = {
    129: "firstaid", 164: "blacksmithing", 165: "leatherworking", 171: "alchemy",
    182: "herbalism", 185: "cooking", 186: "mining", 197: "tailoring",
    202: "engineering", 333: "enchanting", 356: "fishing", 393: "skinning",
}
# Item class 7 (Trade Goods) subclasses gathered by a profession.
GATHERED = {"herbalism": [9], "skinning": [6], "mining": [7]}
# Only these item classes count as materials: Reagent (5), Trade Goods (7),
# Miscellaneous (15). Consumables, gear, ammo and recipes never do.
MATERIAL_CLASSES = {5, 7, 15}


def fetch(table, build, cache, locale=None):
    name = f"{table}_{locale}.csv" if locale else f"{table}.csv"
    path = cache / build / name
    if not path.exists():
        url = f"https://wago.tools/db2/{table}/csv?build={build}"
        if locale:
            url += f"&locale={locale}"
        request = urllib.request.Request(url, headers={"User-Agent": "ForeverJunkItems-data"})
        with urllib.request.urlopen(request, timeout=120) as response:
            data = response.read()
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    return list(csv.DictReader(io.StringIO(path.read_text(encoding="utf-8"))))


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build_data(build, cache):
    skill_lines = fetch("SkillLine", build, cache)
    parent_of = {}
    for row in skill_lines:
        line, parent = int(row["ID"]), int(row["ParentSkillLineID"])
        if parent in PROFESSIONS:
            parent_of[line] = parent
        elif line in PROFESSIONS:
            parent_of[line] = line

    names = {key: set() for key in PROFESSIONS.values()}
    for locale in LOCALES:
        for row in fetch("SkillLine", build, cache, None if locale == "enUS" else locale):
            line = int(row["ID"])
            if line in PROFESSIONS and row["DisplayName_lang"].strip():
                names[PROFESSIONS[line]].add(row["DisplayName_lang"].strip())

    items = {int(r["ID"]): (int(r["ClassID"]), int(r["SubclassID"])) for r in fetch("Item", build, cache)}

    spells = {}
    for row in fetch("SkillLineAbility", build, cache):
        line = int(row["SkillLine"])
        if line in parent_of:
            spells.setdefault(int(row["Spell"]), set()).add(PROFESSIONS[parent_of[line]])

    uses = {key: set() for key in PROFESSIONS.values()}
    for row in fetch("SpellReagents", build, cache):
        owners = spells.get(int(row["SpellID"]))
        if not owners:
            continue
        for index in range(8):
            item = int(row[f"Reagent_{index}"] or 0)
            if item > 0 and items.get(item, (None,))[0] in MATERIAL_CLASSES:
                for key in owners:
                    uses[key].add(item)

    gathered = {key: sorted(i for i, (c, s) in items.items() if c == 7 and s in subs)
                for key, subs in GATHERED.items()}
    lines = {line: PROFESSIONS[parent] for line, parent in parent_of.items()}
    return names, uses, gathered, lines


def render(build, names, uses, gathered, lines):
    out = [
        "-- GENERATED by scripts/make_materials.py from WoW Forever " + build + ": do not edit.",
        "-- Which materials each profession uses (its recipes' reagents) or gathers.",
        "local _, ns = ...",
        "local M = {}",
        "ns.Materials = M",
        "M.BUILD = " + lua_string(build),
        "",
        "-- Profession names as the skill list shows them, in every client language.",
        "M.NAMES = {",
    ]
    for key in sorted(names):
        joined = ", ".join(lua_string(n) for n in sorted(names[key]))
        out.append(f"    {key} = {{ {joined} }},")
    out += ["}", "", "-- Skill line -> profession (Forever adds a second line per profession).", "M.LINES = {"]
    for line in sorted(lines):
        out.append(f"    [{line}] = {lua_string(lines[line])},")
    out += ["}", "", "-- Item IDs used by each profession's recipes.", "M.USES = {"]
    for key in sorted(uses):
        if uses[key]:
            out.append(f"    {key} = {lua_string(','.join(str(i) for i in sorted(uses[key])))},")
    out += ["}", "", "-- Item IDs a gathering profession collects.", "M.GATHERS = {"]
    for key in sorted(gathered):
        out.append(f"    {key} = {lua_string(','.join(str(i) for i in gathered[key]))},")
    out += ["}", ""]
    return "\n".join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--build", default=DEFAULT_BUILD)
    parser.add_argument("--cache", default=str(ROOT / ".cache" / "db2"))
    args = parser.parse_args(argv)
    names, uses, gathered, lines = build_data(args.build, pathlib.Path(args.cache))
    missing = [key for key, found in names.items() if not found]
    if missing:
        print(f"no names for {missing}", file=sys.stderr)
        return 1
    OUTPUT.write_text(render(args.build, names, uses, gathered, lines), encoding="utf-8", newline="\n")
    for key in sorted(uses):
        print(f"{key}: uses {len(uses[key])}, gathers {len(gathered.get(key, []))}, names {len(names[key])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
